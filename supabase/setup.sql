-- 1. TABLES (matches project ER diagram + product_name snapshot on order_items)
CREATE TABLE IF NOT EXISTS public.roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role varchar NOT NULL UNIQUE,
  created_at timestamptz NOT NULL DEFAULT now(),
  encoded_by uuid REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  email text NOT NULL,
  firstname text NOT NULL DEFAULT '',
  lastname text NOT NULL DEFAULT '',
  role_id bigint NOT NULL REFERENCES public.roles(id)
);

CREATE TABLE IF NOT EXISTS public.categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS public.products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  name text NOT NULL,
  description text,
  stock smallint NOT NULL DEFAULT 0 CHECK (stock >= 0),
  image_url text,
  category_id bigint REFERENCES public.categories(id) ON DELETE SET NULL,
  price real NOT NULL DEFAULT 0 CHECK (price >= 0)
);

CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'done',
  total numeric(10, 2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.order_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id bigint REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL DEFAULT '',
  unit_price numeric(10, 2) NOT NULL,
  quantity bigint NOT NULL CHECK (quantity > 0)
);

-- Ensure snapshot column exists if order_items was already created earlier
ALTER TABLE public.order_items
  ADD COLUMN IF NOT EXISTS product_name text NOT NULL DEFAULT '';


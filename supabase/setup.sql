-- 2. HELPER FUNCTION FOR ADMIN ROLE CHECK (avoids RLS recursion on profiles)
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    JOIN public.roles r ON r.id = p.role_id
    WHERE p.id = auth.uid()
      AND r.role = 'admin'
  );
$$;

-- 3. TRIGGER: AUTO-CREATE PROFILE ON SIGN UP (Email/Password + Google OAuth)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  default_role_id bigint;
  meta_first text;
  meta_last text;
  full_name text;
BEGIN
  SELECT id INTO default_role_id
  FROM public.roles
  WHERE role = 'customer'
  LIMIT 1;

  full_name := COALESCE(
    NEW.raw_user_meta_data->>'full_name',
    NEW.raw_user_meta_data->>'name',
    ''
  );

  meta_first := COALESCE(
    NULLIF(TRIM(NEW.raw_user_meta_data->>'firstname'), ''),
    NULLIF(TRIM(NEW.raw_user_meta_data->>'given_name'), ''),
    NULLIF(SPLIT_PART(TRIM(full_name), ' ', 1), ''),
    SPLIT_PART(COALESCE(NEW.email, 'user'), '@', 1)
  );

  meta_last := COALESCE(
    NULLIF(TRIM(NEW.raw_user_meta_data->>'lastname'), ''),
    NULLIF(TRIM(NEW.raw_user_meta_data->>'family_name'), ''),
    NULLIF(TRIM(SUBSTRING(TRIM(full_name) FROM POSITION(' ' IN TRIM(full_name)) + 1)), ''),
    ''
  );

  INSERT INTO public.profiles (id, email, firstname, lastname, role_id)
  VALUES (
    NEW.id,
    COALESCE(NEW.email, ''),
    meta_first,
    meta_last,
    default_role_id
  )
  ON CONFLICT (id) DO NOTHING;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_new_user();

-- 4. TRIGGER: PREVENT CUSTOMERS FROM ESCALATING THEIR OWN ROLE
CREATE OR REPLACE FUNCTION public.prevent_role_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.role_id IS DISTINCT FROM OLD.role_id
     AND auth.uid() IS NOT NULL
     AND NOT public.is_admin() THEN
    RAISE EXCEPTION 'You are not allowed to change your role.' USING ERRCODE = '42501';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_prevent_role_change ON public.profiles;
CREATE TRIGGER trg_prevent_role_change
  BEFORE UPDATE ON public.profiles
  FOR EACH ROW
  EXECUTE FUNCTION public.prevent_role_change();

-- 5. ATOMIC CHECKOUT RPC FUNCTION (server-side pricing, stock validation & decrement)
CREATE OR REPLACE FUNCTION public.place_order(items jsonb)
RETURNS TABLE (new_order_id bigint, order_total numeric)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_uid uuid := auth.uid();
  elem jsonb;
  v_product_id bigint;
  v_qty int;
  v_name text;
  v_price numeric(10, 2);
  v_stock int;
  v_total numeric(10, 2) := 0;
  v_order_id bigint;
BEGIN
  IF current_uid IS NULL THEN
    RAISE EXCEPTION 'Authentication required.' USING ERRCODE = '42501';
  END IF;

  IF public.is_admin() THEN
    RAISE EXCEPTION 'Admins cannot place customer orders.' USING ERRCODE = '42501';
  END IF;

  IF items IS NULL OR jsonb_typeof(items) <> 'array' OR jsonb_array_length(items) = 0 THEN
    RAISE EXCEPTION 'Cart cannot be empty.';
  END IF;

  -- Create the parent order first (rolls back automatically if any item fails)
  INSERT INTO public.orders (user_id, status, total)
  VALUES (current_uid, 'done', 0)
  RETURNING id INTO v_order_id;

  FOR elem IN SELECT * FROM jsonb_array_elements(items)
  LOOP
    v_product_id := (elem->>'product_id')::bigint;
    v_qty := (elem->>'quantity')::int;

    IF v_product_id IS NULL OR v_qty IS NULL OR v_qty <= 0 THEN
      RAISE EXCEPTION 'Invalid product or quantity in cart.';
    END IF;

    -- Lock the product row and read authoritative name, price, and stock from DB
    SELECT name, price::numeric(10, 2), stock
    INTO v_name, v_price, v_stock
    FROM public.products
    WHERE id = v_product_id
    FOR UPDATE;

    IF NOT FOUND THEN
      RAISE EXCEPTION 'Product % no longer exists.', v_product_id;
    END IF;

    IF v_stock < v_qty THEN
      RAISE EXCEPTION 'Not enough stock for "%" (available: %).', v_name, v_stock;
    END IF;

    -- Snapshot product name & unit price paid into order_items
    INSERT INTO public.order_items (order_id, product_id, product_name, unit_price, quantity)
    VALUES (v_order_id, v_product_id, v_name, v_price, v_qty);

    -- Decrement available stock in the same atomic transaction
    UPDATE public.products
    SET stock = stock - v_qty
    WHERE id = v_product_id;

    v_total := v_total + (v_price * v_qty);
  END LOOP;

  UPDATE public.orders
  SET total = v_total
  WHERE id = v_order_id;

  RETURN QUERY SELECT v_order_id, v_total;
END;
$$;

GRANT EXECUTE ON FUNCTION public.place_order(jsonb) TO authenticated;

